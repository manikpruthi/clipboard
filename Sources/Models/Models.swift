import AppKit
import CryptoKit
import ImageIO
import UniformTypeIdentifiers

struct ClipboardItem: Identifiable {
    let id: UUID
    let type: ItemType
    let timestamp: Date
    var pinned: Bool
    let text: String?
    /// Always PNG-encoded.
    let imageData: Data?
    /// Size in pixels, not points.
    let imageSize: CGSize?
    /// Small pre-decoded image for the row icon, so rows never decode the full image.
    let thumbnail: NSImage?
    let digest: SHA256.Digest
    let preview: String
    /// Every representation the source app put on the pasteboard (RTF, HTML, file URLs, …),
    /// in the app's preference order, so pasting restores formatting. Empty when the copy was
    /// too large to keep in full; pasting then falls back to plain text or PNG.
    let snapshot: [[Representation]]
    /// Bytes this entry keeps in memory (used for the history byte cap).
    let byteCount: Int

    struct Representation {
        let type: NSPasteboard.PasteboardType
        let data: Data
    }

    enum ItemType: Equatable {
        case text
        case image
    }

    func contentMatches(_ other: ClipboardItem) -> Bool {
        type == other.type && digest == other.digest
    }

    /// Markers set by password managers and other apps for data that must not be recorded.
    /// See http://nspasteboard.org
    private static let ignoredTypes: Set<NSPasteboard.PasteboardType> = [
        NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType"),
        NSPasteboard.PasteboardType("org.nspasteboard.TransientType"),
        NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType"),
        NSPasteboard.PasteboardType("com.agilebits.onepassword"),
    ]

    static let maxImageBytes = 25 * 1024 * 1024
    private static let maxSnapshotBytes = 25 * 1024 * 1024
    private static let thumbnailPixels = 96

    static func fromPasteboard() -> ClipboardItem? {
        let pb = NSPasteboard.general
        let types = Set(pb.types ?? [])
        guard types.isDisjoint(with: ignoredTypes) else { return nil }

        let string = pb.string(forType: .string)
        let hasText = string?.contains { !$0.isWhitespace } ?? false
        let hasImage = types.contains(.png) || types.contains(.tiff)

        // Text wins when both are present (spreadsheet cells, rich text and Finder files all
        // carry a rendered image alongside the text). The exception is a browser "Copy Image",
        // where the only text is the image's URL.
        let snapshot = snapshot(of: pb)
        if hasImage, !hasText || isBareURL(string ?? "") {
            if let item = imageItem(from: pb, snapshot: snapshot) { return item }
        }
        if let string, hasText {
            return textItem(string, snapshot: snapshot)
        }
        return nil
    }

    /// Reads every concrete representation of every pasteboard item. Skips types the system
    /// synthesizes on demand (`dyn.*`) and file promises, which would make the source app do work.
    private static func snapshot(of pb: NSPasteboard) -> [[Representation]] {
        var total = 0
        var items: [[Representation]] = []
        for pbItem in pb.pasteboardItems ?? [] {
            var reps: [Representation] = []
            for type in pbItem.types {
                let raw = type.rawValue
                guard !raw.hasPrefix("dyn."), !raw.localizedCaseInsensitiveContains("promise"),
                      let data = pbItem.data(forType: type)
                else { continue }
                total += data.count
                guard total <= maxSnapshotBytes else { return [] }
                reps.append(Representation(type: type, data: data))
            }
            if !reps.isEmpty { items.append(reps) }
        }
        return items
    }

    private static func bytes(of snapshot: [[Representation]]) -> Int {
        snapshot.reduce(0) { $0 + $1.reduce(0) { $0 + $1.data.count } }
    }

    private static func isBareURL(_ string: String) -> Bool {
        let trimmed = string.trimmingCharacters(in: .whitespacesAndNewlines)
        guard !trimmed.contains(where: \.isWhitespace),
              let url = URL(string: trimmed), let scheme = url.scheme?.lowercased()
        else { return false }
        return ["http", "https", "file", "data"].contains(scheme)
    }

    private static func textItem(_ string: String, snapshot: [[Representation]]) -> ClipboardItem {
        // Only the start of the text is shown, so don't flatten megabytes of whitespace.
        let flat = string.prefix(1000).split(whereSeparator: \.isWhitespace).joined(separator: " ")
        return ClipboardItem(id: UUID(), type: .text, timestamp: Date(), pinned: false,
                             text: string, imageData: nil, imageSize: nil, thumbnail: nil,
                             digest: SHA256.hash(data: Data(string.utf8)),
                             preview: String(flat.prefix(200)),
                             snapshot: snapshot,
                             byteCount: string.utf8.count + bytes(of: snapshot))
    }

    private static func imageItem(from pb: NSPasteboard, snapshot: [[Representation]]) -> ClipboardItem? {
        let pngData = pb.data(forType: .png)
        let isPNG = pngData != nil
        guard let raw = pngData ?? pb.data(forType: .tiff),
              let source = CGImageSourceCreateWithData(raw as CFData, nil),
              CGImageSourceGetCount(source) > 0,
              let props = CGImageSourceCopyPropertiesAtIndex(source, 0, nil) as? [CFString: Any],
              let width = props[kCGImagePropertyPixelWidth] as? Int,
              let height = props[kCGImagePropertyPixelHeight] as? Int
        else { return nil }

        guard let png = isPNG ? raw : encodePNG(source), png.count <= maxImageBytes else { return nil }

        let thumbOptions: [CFString: Any] = [
            kCGImageSourceCreateThumbnailFromImageAlways: true,
            kCGImageSourceCreateThumbnailWithTransform: true,
            kCGImageSourceThumbnailMaxPixelSize: thumbnailPixels,
        ]
        let thumbnail = CGImageSourceCreateThumbnailAtIndex(source, 0, thumbOptions as CFDictionary)
            .map { NSImage(cgImage: $0, size: .zero) }

        return ClipboardItem(id: UUID(), type: .image, timestamp: Date(), pinned: false,
                             text: nil, imageData: png,
                             imageSize: CGSize(width: width, height: height),
                             thumbnail: thumbnail,
                             digest: SHA256.hash(data: png),
                             preview: "[Image \(width)×\(height)]",
                             snapshot: snapshot,
                             byteCount: png.count + bytes(of: snapshot))
    }

    private static func encodePNG(_ source: CGImageSource) -> Data? {
        let out = NSMutableData()
        guard let dest = CGImageDestinationCreateWithData(out, UTType.png.identifier as CFString, 1, nil)
        else { return nil }
        CGImageDestinationAddImageFromSource(dest, source, 0, nil)
        guard CGImageDestinationFinalize(dest) else { return nil }
        return out as Data
    }

    @MainActor
    func writeToPasteboard() {
        let pb = NSPasteboard.general
        pb.clearContents()
        if !snapshot.isEmpty {
            restoreSnapshot(to: pb)
            return
        }
        switch type {
        case .text:
            if let text { pb.setString(text, forType: .string) }
        case .image:
            guard let imageData else { return }
            // PNG goes on directly; TIFF is only encoded if an app actually asks for it.
            let provider = TIFFProvider(png: imageData)
            Self.activeProvider = provider
            let entry = NSPasteboardItem()
            entry.setData(imageData, forType: .png)
            entry.setDataProvider(provider, forTypes: [.tiff])
            pb.writeObjects([entry])
        }
    }

    @MainActor
    private func restoreSnapshot(to pb: NSPasteboard) {
        let entries = snapshot.map { reps in
            let entry = NSPasteboardItem()
            for rep in reps { entry.setData(rep.data, forType: rep.type) }
            return entry
        }
        // Images copied as TIFF only also get the PNG we converted, for apps that want PNG.
        if type == .image, let imageData, let first = entries.first, !first.types.contains(.png) {
            first.setData(imageData, forType: .png)
        }
        pb.writeObjects(entries)
    }

    /// Keeps the lazy TIFF provider alive while its pasteboard contents are current.
    @MainActor private static var activeProvider: TIFFProvider?

    static func simulatePaste() {
        guard let source = CGEventSource(stateID: .hidSystemState) else { return }
        let keyDown = CGEvent(keyboardEventSource: source, virtualKey: 0x09, keyDown: true)
        let keyUp = CGEvent(keyboardEventSource: source, virtualKey: 0x09, keyDown: false)
        keyDown?.flags = .maskCommand
        keyUp?.flags = .maskCommand
        keyDown?.post(tap: .cghidEventTap)
        keyUp?.post(tap: .cghidEventTap)
    }
}

private final class TIFFProvider: NSObject, NSPasteboardItemDataProvider, @unchecked Sendable {
    private let png: Data

    init(png: Data) {
        self.png = png
    }

    func pasteboard(_ pasteboard: NSPasteboard?, item: NSPasteboardItem,
                    provideDataForType type: NSPasteboard.PasteboardType) {
        guard type == .tiff, let tiff = NSBitmapImageRep(data: png)?.tiffRepresentation else { return }
        item.setData(tiff, forType: .tiff)
    }
}
